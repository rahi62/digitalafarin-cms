#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const __filename = fileURLToPath(import.meta.url);
const packageRoot = path.resolve(path.dirname(__filename), "..");
const args = process.argv.slice(2);
const command = args[0] && !args[0].startsWith("--") ? args.shift() : "scaffold";

if (command !== "scaffold") {
  console.error("Usage: digitalafarin-cms-admin scaffold [--dir cms-admin] [--base-path /cms] [--api-url URL] [--port 3001] [--skip-install] [--force]");
  process.exit(2);
}

function arg(name, fallback) {
  const index = args.indexOf(name);
  return index >= 0 && args[index + 1] ? args[index + 1] : fallback;
}

function has(name) {
  return args.includes(name);
}

function normalizeBasePath(value) {
  const raw = String(value || "/cms").trim();
  if (!raw || raw === "/") return "";
  const withLeadingSlash = raw.startsWith("/") ? raw : `/${raw}`;
  return withLeadingSlash.replace(/\/+$/, "");
}

function copyTree(source, destination) {
  fs.mkdirSync(destination, { recursive: true });
  for (const entry of fs.readdirSync(source, { withFileTypes: true })) {
    const from = path.join(source, entry.name);
    const to = path.join(destination, entry.name);
    if (entry.isDirectory()) copyTree(from, to);
    else fs.copyFileSync(from, to);
  }
}

function run(command, commandArgs, cwd) {
  console.log(`> ${command} ${commandArgs.join(" ")}`);
  const result = spawnSync(command, commandArgs, {
    cwd,
    stdio: "inherit",
    shell: process.platform === "win32",
  });
  if (result.status !== 0) throw new Error(`${command} exited with code ${result.status}`);
}

const destination = path.resolve(process.cwd(), arg("--dir", "cms-admin"));
const basePath = normalizeBasePath(arg("--base-path", "/cms"));
const apiUrl = arg("--api-url", "http://127.0.0.1:8000/api/cms/v1");
const port = arg("--port", "3001");
const force = has("--force");
const skipInstall = has("--skip-install");
const route = basePath || "/cms";
const browserApiUrl = `${route}/api-proxy`;

if (fs.existsSync(destination) && fs.readdirSync(destination).length > 0 && !force) {
  throw new Error(`Target directory is not empty: ${destination}. Use --force only if you intend to overwrite generated CMS Admin files.`);
}

fs.mkdirSync(destination, { recursive: true });
copyTree(path.join(packageRoot, "src"), path.join(destination, "src"));
fs.copyFileSync(path.join(packageRoot, "next.config.ts"), path.join(destination, "next.config.ts"));
fs.copyFileSync(path.join(packageRoot, "tsconfig.json"), path.join(destination, "tsconfig.json"));

const ownPackage = JSON.parse(fs.readFileSync(path.join(packageRoot, "package.json"), "utf8"));
const appPackage = {
  name: "digitalafarin-cms-admin-app",
  version: ownPackage.version,
  private: true,
  scripts: {
    dev: "next dev",
    build: "next build",
    start: "next start",
    typecheck: "tsc --noEmit"
  },
  dependencies: ownPackage.dependencies,
  devDependencies: ownPackage.devDependencies
};
fs.writeFileSync(path.join(destination, "package.json"), `${JSON.stringify(appPackage, null, 2)}\n`);

const env = [
  `NEXT_PUBLIC_DIGITALAFARIN_CMS_ADMIN_BASE_PATH=${basePath || "/"}`,
  `NEXT_PUBLIC_API_URL=${browserApiUrl}`,
  `DIGITALAFARIN_CMS_API_URL=${apiUrl}`,
  `PORT=${port}`,
  "",
].join("\n");
fs.writeFileSync(path.join(destination, ".env.local"), env);
fs.writeFileSync(path.join(destination, ".env.example"), env);

const deployDir = path.join(destination, "deploy");
fs.mkdirSync(deployDir, { recursive: true });
const nginx = `# Include inside the HTTPS server block for your main website.\n# Keep proxy_pass without a trailing slash so Next.js receives the ${route} prefix.\nlocation = ${route} {\n    return 308 ${route}/;\n}\n\nlocation ${route}/ {\n    proxy_http_version 1.1;\n    proxy_set_header Host $host;\n    proxy_set_header X-Real-IP $remote_addr;\n    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;\n    proxy_set_header X-Forwarded-Proto $scheme;\n    proxy_set_header Upgrade $http_upgrade;\n    proxy_set_header Connection \"upgrade\";\n    proxy_pass http://127.0.0.1:${port};\n}\n`;
fs.writeFileSync(path.join(deployDir, "nginx.cms.conf"), nginx);

const readme = `# DigitalAfarin CMS Admin app\n\nGenerated by @digitalafarin/cms-admin.\n\n## Development\n\n\`\`\`bash\nnpm install\nnpm run dev\n\`\`\`\n\nOpen: http://localhost:${port}${route}/\n\n## Production\n\n\`\`\`bash\nnpm run build\nPORT=${port} npm start\n\`\`\`\n\nAdd the contents of \`deploy/nginx.cms.conf\` to the HTTPS server block for your main domain.\n\nBrowser requests use the same-origin \`${browserApiUrl}\` proxy. The server-side proxy forwards them to \`DIGITALAFARIN_CMS_API_URL=${apiUrl}\`, so a separate Django API subdomain does not require browser CORS access for the CMS Admin.\n`;
fs.writeFileSync(path.join(destination, "README.md"), readme);

if (!skipInstall) run("npm", ["install"], destination);

console.log("\nDigitalAfarin CMS Admin scaffolded successfully.");
console.log(`Directory: ${destination}`);
console.log(`Base path: ${route}`);
console.log(`Browser API proxy: ${browserApiUrl}`);
console.log(`Django upstream: ${apiUrl}`);
console.log(`Port: ${port}`);
console.log(`Nginx snippet: ${path.join(destination, "deploy", "nginx.cms.conf")}`);
